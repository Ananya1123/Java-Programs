
//USING LOOP- LOOPS IS USED FOR EXECUTING A BLOCK OF STATMENTS REPEATEDLY UNTIL A PARTICULAR CONDITION IS SATISFIED. A LOOP CONSIST OF AN INITIALIZATION STATEMENT, A TEST CONDITION AND AN INCREMENT STATEMENT.
//PROGRAM TO PRINT "HELLO WORLD" 6 TIMES USING FOR LOOP.
public class BASICS{
    public static void main(String args[]){
        for(int i=0;i<6;i++){
            System.out.println("HELLO WORLD");
        }

    }
}